/**
 * Hostname without scheme or `www`, for display in UI and social cards.
 * Derived rather than hard-coded so it follows `siteConfig.url` automatically.
 */
export function displayDomain(): string {
  return siteConfig.url.replace(/^https?:\/\//, '').replace(/^www\./, '');
}

