/** Production origin. No trailing slash, no `www` — this is the canonical host. */
const PRODUCTION_URL = 'https://rfpsoftwareguide.com';

/**
 * Every absolute URL on the site derives from this: canonicals, `metadataBase`,
 * Open Graph and Twitter tags, JSON-LD, the sitemap, robots.txt and the RSS feed.
 *
 * `NEXT_PUBLIC_SITE_URL` overrides it so preview and staging deployments emit
 * their own origin instead of claiming the production one. It is read at build
 * time; a trailing slash is stripped so callers can always append a path.
 */
function resolveSiteUrl(): string {
  const configured = process.env.NEXT_PUBLIC_SITE_URL?.trim();
  if (!configured) return PRODUCTION_URL;
  return configured.replace(/\/+$/, '');
}

